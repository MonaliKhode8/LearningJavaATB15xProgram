package ex_15_Functions;

public class Lab003_Simple_Method {
    public static void main(String[] args) {

    }

    static void non_return_function() {
        System.out.println("Print something no return or return type");
    }

    static int return_int() {
        System.out.println("Print something and return");
        return 10;
    }

    static boolean return_boolean() {
        System.out.println("Print something and return");
        return true;
    }

    static float return_float_pi_value() {
        System.out.println("Print something and return");
        return 3.14f;
    }
}
