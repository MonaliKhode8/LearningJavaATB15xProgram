package ex_06_Java_Operator_Incre_Decre;

public class Lab004_Pre_Increment_ex1 {
    public static void main(String[] args) {


        int x =10;
        System.out.println(x);
        System.out.println(++x);

        int a = 10;
        int b = ++a;
        System.out.println(b);
        System.out.println(a);

    }
}
